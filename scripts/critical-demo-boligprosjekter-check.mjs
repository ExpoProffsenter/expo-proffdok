import assert from 'node:assert/strict';
import fs from 'node:fs';
import {initialState,activeUnits,resizeEntrance,acceptUnit,addOrder,shiftPlan,validateSelection,restoreState,STORAGE_KEY} from '../public/demo/boligprosjekter/model.mjs';

const s=initialState();
assert.equal(activeUnits(s).length,312);
assert.equal(s.entrances.length,13);
assert.equal(new Set(activeUnits(s).map(u=>u.id)).size,312);
assert.equal(s.units['B1:3:2'].number,'H0302');
const original=structuredClone(s.units['B1:3:2']);
const cropped=resizeEntrance(s,'B1',[4,4]);
assert.equal(cropped.after,8);
assert.equal(cropped.preserved,16);
assert.deepEqual(s.units['B1:3:2'],original,'Hiding a floor must preserve its complete project identity/history.');
resizeEntrance(s,'B1',[4,4,4,4,4,4,2]);
assert.deepEqual(s.units['B1:3:2'],original);
assert.equal(activeUnits(s).length,314);
assert.throws(()=>resizeEntrance(s,'B1',[0]),/1–20/);
assert.throws(()=>resizeEntrance(s,'B1',Array(21).fill(4)),/1–20/);
assert.match(validateSelection(['shower','black']),/kombineres/);
assert.match(validateSelection(['walltap']),/krever/);
assert.equal(validateSelection(['walltap','concealed']),'');
assert.throws(()=>acceptUnit(s,'B1:3:2'),/låst/);
const u=s.units['B1:3:2'];
const signed=JSON.stringify(u.accepted);
s.factor=1.06;
assert.equal(JSON.stringify(u.accepted),signed,'A new project price factor cannot rewrite an accepted price.');
u.editing=true;u.selected=[...u.accepted.ids,'socket'];
acceptUnit(s,u.id);
assert.equal(u.accepted.version,2);
assert.equal(JSON.stringify(u.history[0]),signed);
assert.throws(()=>addOrder(s,u.id,'Innbyggingsvarer'),/allerede/);
addOrder(s,u.id,'Sanitærutstyr');
assert.throws(()=>addOrder(s,u.id,'Sanitærutstyr'),/allerede/);
const unsigned=activeUnits(s).find(x=>!x.accepted);
assert.throws(()=>addOrder(s,unsigned.id,'Sanitærutstyr'),/Godkjenn/);
s.notices=[{id:'N1',entrance:'B1',status:'Godkjent eksempel'},{id:'N2',entrance:'B2',status:'Godkjent eksempel'}];
assert.equal(shiftPlan(s,u.id,'2026-11-09'),1);
assert.equal(s.notices[0].status,'Må godkjennes på nytt');
assert.equal(s.notices[1].status,'Godkjent eksempel');
assert.equal(shiftPlan(s,u.id,'2026-11-09'),0);
assert.equal(activeUnits(restoreState(JSON.stringify(s))).length,314);
assert.equal(restoreState('broken'),null);
assert.equal(restoreState('{"version":1}'),null);
assert.match(STORAGE_KEY,/prototype/);
for(const path of ['app.mjs','model.mjs']){
 const source=fs.readFileSync('public/demo/boligprosjekter/'+path,'utf8');
 assert(!/\bfetch\s*\(|XMLHttpRequest|WebSocket|sendBeacon|createClient|supabase\.(?:rpc|from)|localStorage\.clear\s*\(/.test(source),`Prototype must never call a service or clear other app data: ${path}`);
}
const html=fs.readFileSync('public/demo/boligprosjekter/index.html','utf8');
assert(html.includes("connect-src 'none'"));
assert(!/https?:\/\//.test(html));
console.log('PASS boligprosjekter prototype: 312 unique units, reversible building changes, locked acceptance, dependency rules, order deduplication, reminder reapproval, persistence and no-network isolation.');
