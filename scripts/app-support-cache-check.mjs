import assert from 'node:assert/strict';
import { isolateSupportCaches } from '../src/modules/access/appSupportBrowserStorage.mjs';
const {JSDOM}=await import(process.env.KSHMS_JSDOM_PATH||'jsdom');
const dom=new JSDOM('',{url:'https://qa.invalid'}),w=dom.window;
const original=w.localStorage,session=w.sessionStorage,id='81000000-0000-4000-8000-000000000001';
original.setItem('offer','own draft');original.setItem('sb-qa-auth-token','actor auth');
session.setItem('route','own route');
let opened,removed;
Object.defineProperty(w,'indexedDB',{value:{open:(...args)=>{opened=args;},deleteDatabase:name=>{removed=name;},databases:async()=>[{name:'own-db'},{name:`expo-support:${id}:customer-db`,version:2}]}});
isolateSupportCaches(w,id,original,session);
assert.equal(w.localStorage.getItem('offer'),null);assert.equal(w.localStorage.getItem('sb-qa-auth-token'),'actor auth');
w.localStorage.setItem('offer','customer draft');assert.equal(original.getItem('offer'),'own draft');
assert.equal(w.localStorage.getItem('offer'),'customer draft');assert.equal(w.sessionStorage.getItem('route'),null);
w.indexedDB.open('drafts',3);assert.deepEqual(opened,[`expo-support:${id}:drafts`,3]);
w.indexedDB.deleteDatabase('drafts');assert.equal(removed,`expo-support:${id}:drafts`);
assert.deepEqual(await w.indexedDB.databases(),[{name:'customer-db',version:2}]);
const seen=[];w.addEventListener('storage',e=>seen.push([e.key,e.newValue]));
w.dispatchEvent(new w.StorageEvent('storage',{key:'offer',newValue:'other tab own draft',storageArea:original}));assert.equal(seen.length,0);
w.dispatchEvent(new w.StorageEvent('storage',{key:`expo-support:${id}:offer`,newValue:'same support draft',storageArea:original}));assert.deepEqual(seen,[['offer','same support draft']]);
w.dispatchEvent(new w.StorageEvent('storage',{key:'sb-qa-auth-token',newValue:'refreshed',storageArea:original}));assert.equal(seen[1][0],'sb-qa-auth-token');
w.localStorage.clear();assert.equal(original.getItem('offer'),'own draft');assert.equal(original.getItem('sb-qa-auth-token'),'actor auth');
dom.window.close();console.log('app-support-cache: PASS – own drafts retained, customer namespace, IndexedDB, cross-tab events and shared actor authentication');
