-- Expo ProffDok – systemadminstyrt e-postutsending
-- Skiller nødvendige driftsmeldinger fra samtykkebasert markedsføring.

create table if not exists public.marketing_email_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email_opt_in boolean not null default false,
  consent_at timestamptz,
  consent_source text not null default 'app_settings',
  unsubscribed_at timestamptz,
  unsubscribe_token uuid not null default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint marketing_email_preferences_token_unique unique (unsubscribe_token),
  constraint marketing_email_preferences_source_check check (
    consent_source in ('app_settings', 'email_unsubscribe')
  ),
  constraint marketing_email_preferences_consent_check check (
    not email_opt_in or consent_at is not null
  )
);

create table if not exists public.marketing_email_preference_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  email_opt_in boolean not null,
  source text not null,
  created_at timestamptz not null default now(),
  constraint marketing_email_preference_events_source_check check (
    source in ('app_settings', 'email_unsubscribe')
  )
);

create table if not exists public.systemadmin_email_campaigns (
  id uuid primary key default gen_random_uuid(),
  client_request_id uuid not null unique,
  created_by uuid not null,
  message_type text not null,
  recipient_group text not null,
  subject text not null,
  message text not null,
  recipient_count integer not null default 0,
  sent_count integer not null default 0,
  failed_count integer not null default 0,
  status text not null default 'processing',
  resend_batch_ids jsonb not null default '[]'::jsonb,
  error_summary text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint systemadmin_email_campaigns_message_type_check check (
    message_type in ('operational', 'marketing')
  ),
  constraint systemadmin_email_campaigns_recipient_group_check check (
    recipient_group in ('active', 'pending', 'all_registered', 'systemadmins')
  ),
  constraint systemadmin_email_campaigns_status_check check (
    status in ('processing', 'sent', 'partial', 'failed')
  ),
  constraint systemadmin_email_campaigns_count_check check (
    recipient_count >= 0 and sent_count >= 0 and failed_count >= 0
  )
);

alter table public.marketing_email_preferences enable row level security;
alter table public.marketing_email_preference_events enable row level security;
alter table public.systemadmin_email_campaigns enable row level security;

-- Preferansetoken, samtykkehistorikk og utsendingslogg skal aldri leses direkte
-- fra nettleseren. Brukerflaten går via de avgrensede RPC-ene under.
revoke all on table public.marketing_email_preferences from public, anon, authenticated, service_role;
revoke all on table public.marketing_email_preference_events from public, anon, authenticated, service_role;
revoke all on table public.systemadmin_email_campaigns from public, anon, authenticated, service_role;
grant select, update on table public.marketing_email_preferences to service_role;
grant select, insert, update on table public.systemadmin_email_campaigns to service_role;

