  on public.systemadmin_email_campaigns (created_by, created_at desc);

create or replace function public.log_marketing_email_preference_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' or old.email_opt_in is distinct from new.email_opt_in then
    insert into public.marketing_email_preference_events (
      user_id,
      email_opt_in,
      source
    ) values (
      new.user_id,
      new.email_opt_in,
      new.consent_source
    );
  end if;
  return new;
end;
$$;

drop trigger if exists marketing_email_preference_event_trigger
  on public.marketing_email_preferences;
create trigger marketing_email_preference_event_trigger
after insert or update of email_opt_in on public.marketing_email_preferences
for each row execute function public.log_marketing_email_preference_event();

create or replace function public.get_my_marketing_email_preference()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.marketing_email_preferences%rowtype;
begin
  if v_uid is null then
    raise exception 'Du må være innlogget.' using errcode = '42501';
  end if;

  select * into v_row
  from public.marketing_email_preferences
  where user_id = v_uid;

  return jsonb_build_object(
    'email_opt_in', coalesce(v_row.email_opt_in, false),
    'consent_at', v_row.consent_at,
    'unsubscribed_at', v_row.unsubscribed_at
  );
end;
$$;

create or replace function public.set_my_marketing_email_preference(p_opt_in boolean)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_existing public.marketing_email_preferences%rowtype;
  v_row public.marketing_email_preferences%rowtype;
begin
  if v_uid is null then
    raise exception 'Du må være innlogget.' using errcode = '42501';
  end if;
  if p_opt_in is null then
    raise exception 'E-postvalget mangler.' using errcode = '22023';
  end if;

  select * into v_existing
  from public.marketing_email_preferences
  where user_id = v_uid;

  if found and v_existing.email_opt_in = p_opt_in then
    v_row := v_existing;
  else
    insert into public.marketing_email_preferences (
      user_id,
      email_opt_in,
      consent_at,
      consent_source,
      unsubscribed_at,
      updated_at
    ) values (
      v_uid,
      p_opt_in,
      case when p_opt_in then now() else null end,
      'app_settings',
      case when p_opt_in then null else now() end,
      now()
    )
    on conflict (user_id) do update
      set email_opt_in = excluded.email_opt_in,
          consent_at = case
            when excluded.email_opt_in then now()
            else public.marketing_email_preferences.consent_at
          end,
          consent_source = 'app_settings',
          unsubscribed_at = case when excluded.email_opt_in then null else now() end,
          updated_at = now()
    returning * into v_row;
  end if;

  return jsonb_build_object(
    'email_opt_in', v_row.email_opt_in,
    'consent_at', v_row.consent_at,
    'unsubscribed_at', v_row.unsubscribed_at
  );
end;
$$;

revoke all on function public.log_marketing_email_preference_event() from public, anon, authenticated;
revoke all on function public.get_my_marketing_email_preference() from public, anon;
revoke all on function public.set_my_marketing_email_preference(boolean) from public, anon;
grant execute on function public.get_my_marketing_email_preference() to authenticated;
grant execute on function public.set_my_marketing_email_preference(boolean) to authenticated;

